-- v0.27 workspace module activation, safe to apply more than once.
-- Existing workspaces default to all registered modules enabled.
CREATE TABLE IF NOT EXISTS workspace_modules (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id varchar(64) NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    module_id varchar(64) NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_workspace_modules_workspace_module UNIQUE (workspace_id, module_id)
);
CREATE INDEX IF NOT EXISTS ix_workspace_modules_workspace_id ON workspace_modules(workspace_id);
