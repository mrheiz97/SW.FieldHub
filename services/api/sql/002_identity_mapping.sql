-- FieldHub v0.22: additive identity migration for existing PostgreSQL databases.
-- BACK UP the database before applying. Execute once using psql -v ON_ERROR_STOP=1 -1.
-- This migration deliberately retains memberships.subject for the old API until cutover.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS users (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    display_name varchar(160),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS external_identities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    issuer varchar(512) NOT NULL,
    subject varchar(255) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_external_identity UNIQUE (issuer, subject)
);
CREATE INDEX IF NOT EXISTS ix_external_identities_user_id ON external_identities(user_id);

ALTER TABLE memberships ADD COLUMN IF NOT EXISTS user_id uuid;
-- Prevent a pre-existing ambiguous subject from being silently linked.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM memberships WHERE subject IS NULL OR length(trim(subject)) = 0
    ) THEN
        RAISE EXCEPTION 'Invalid legacy membership subject';
    END IF;
END $$;

-- The issuer must be supplied explicitly: no guessing which IdP issued legacy subjects.
-- psql variable :legacy_issuer must be set to the exact verified token iss claim.
CREATE TEMP TABLE _legacy_issuer (value text NOT NULL CHECK (length(value) > 0)) ON COMMIT DROP;
INSERT INTO _legacy_issuer(value) VALUES (:'legacy_issuer');

CREATE TEMP TABLE _legacy_users ON COMMIT DROP AS
SELECT m.subject, gen_random_uuid() AS user_id
FROM memberships m
WHERE NOT EXISTS (
    SELECT 1 FROM external_identities e
    JOIN _legacy_issuer i ON e.issuer = i.value
    WHERE e.subject = m.subject
)
GROUP BY m.subject;

INSERT INTO users(id) SELECT user_id FROM _legacy_users;
INSERT INTO external_identities(user_id, issuer, subject)
SELECT l.user_id, i.value, l.subject FROM _legacy_users l CROSS JOIN _legacy_issuer i;

-- Reject conflicting pre-existing user IDs rather than overwriting them.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM memberships m
        JOIN external_identities e ON e.subject = m.subject
        JOIN _legacy_issuer i ON e.issuer = i.value
        WHERE m.user_id IS NOT NULL AND m.user_id <> e.user_id
    ) THEN
        RAISE EXCEPTION 'Conflicting membership identity mapping';
    END IF;
END $$;

UPDATE memberships m
SET user_id = e.user_id
FROM external_identities e, _legacy_issuer i
WHERE e.issuer = i.value AND e.subject = m.subject AND m.user_id IS NULL;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM memberships WHERE user_id IS NULL) THEN
        RAISE EXCEPTION 'Membership identity backfill incomplete';
    END IF;
END $$;

ALTER TABLE memberships ALTER COLUMN user_id SET NOT NULL;
ALTER TABLE memberships
    ADD CONSTRAINT fk_membership_user FOREIGN KEY (user_id) REFERENCES users(id);
CREATE INDEX IF NOT EXISTS ix_memberships_user_id ON memberships(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_membership_workspace_user ON memberships(workspace_id, user_id);
